def get_central_directory():
    if os.path.exists(CD_FILE) and os.path.getsize(CD_FILE) == CD_SIZE:
        print('Using cached central directory...')
        with open(CD_FILE, 'rb') as f:
            return f.read()
    print('Downloading central directory from Zenodo via HTTP Range (2 MB)...')
    req = urllib.request.Request(ZENODO_ZIP_URL, headers={'Range': f'bytes={CD_OFFSET}-{CD_OFFSET + CD_SIZE - 1}'})
    data = urllib.request.urlopen(req).read()
    with open(CD_FILE, 'wb') as f:
        f.write(data)
    print(f'Cached central directory ({len(data)} bytes).')
    return data

def parse_central_directory(cd_data):
    pos = 0
    entries = {}
    while pos < len(cd_data):
        if cd_data[pos:pos+4] != b'PK\x01\x02':
            break
        header = cd_data[pos:pos+46]
        sig, ver_made, ver_need, flags, method, mod_time, mod_date, crc32, comp_size, uncomp_size, name_len, extra_len, comm_len, disk_start, int_attr, ext_attr, local_hdr_offset = struct.unpack('<4sHHHHHHIIIHHHHHII', header)
        name = cd_data[pos+46:pos+46+name_len].decode('utf-8', errors='ignore')
        if name.endswith('.npy'):
            parts = name.split('/')
            sp = parts[0]
            if sp not in entries:
                entries[sp] = []
            entries[sp].append({
                'name': name,
                'filename': parts[-1],
                'method': method,
                'comp_size': comp_size,
                'uncomp_size': uncomp_size,
                'local_hdr_offset': local_hdr_offset
            })
        pos += 46 + name_len + extra_len + comm_len
    return entries

def fetch_single_npy(entry):
    fetch_len = 30 + 300 + entry['comp_size']
    req = urllib.request.Request(ZENODO_ZIP_URL, headers={'Range': f'bytes={entry["local_hdr_offset"]}-{entry["local_hdr_offset"] + fetch_len}'})
    raw = urllib.request.urlopen(req).read()
    loc_sig, loc_ver, loc_flags, loc_method, loc_mtime, loc_mdate, loc_crc, loc_csize, loc_usize, loc_nlen, loc_xlen = struct.unpack('<4sHHHHHIIIHH', raw[:30])
    file_data = raw[30 + loc_nlen + loc_xlen : 30 + loc_nlen + loc_xlen + loc_csize]
    decomp = zlib.decompress(file_data, -15) if loc_method == 8 else file_data
    return np.load(io.BytesIO(decomp))

def compute_mel_frequencies(n_mels=224, fmin=50.0, fmax=11025.0):
    m_min = 2595.0 * np.log10(1.0 + fmin / 700.0)
    m_max = 2595.0 * np.log10(1.0 + fmax / 700.0)
    m_pts = np.linspace(m_min, m_max, n_mels)
    f_pts = 700.0 * (10.0 ** (m_pts / 2595.0) - 1.0)
    return f_pts

def download_and_slice_audio(xc_audio_name, sec_i, sec_f, output_path):
    if os.path.exists(output_path) and os.path.getsize(output_path) > 1000:
        return True
    ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
    clean_id = ''.join([c for c in xc_audio_name if c.isdigit()])
    xc_url = f'https://xeno-canto.org/{clean_id}/download'
    temp_mp3 = output_path + '.full.mp3'
    try:
        req = urllib.request.Request(xc_url, headers={'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'})
        with urllib.request.urlopen(req, timeout=15) as resp:
            with open(temp_mp3, 'wb') as f:
                f.write(resp.read())
        duration = max(0.8, float(sec_f) - float(sec_i))
        cmd = [
            ffmpeg_exe, '-y',
            '-ss', str(sec_i),
            '-i', temp_mp3,
            '-t', str(duration),
            '-acodec', 'libmp3lame',
            '-b:a', '128k',
            output_path
        ]
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if os.path.exists(temp_mp3):
            os.remove(temp_mp3)
        return os.path.exists(output_path) and os.path.getsize(output_path) > 500
    except Exception as e:
        print(f'Audio download error for {xc_audio_name}: {e}')
        if os.path.exists(temp_mp3):
            try:
                os.remove(temp_mp3)
            except:
                pass
        return False

def main():
    print('Starting dataset preparation pipeline...')
    meta_path = os.path.join(DATA_DIR, 'metadata.csv')
    df = pd.read_csv(meta_path, sep=';')
    print(f'Loaded metadata: {len(df)} entries.')

    cd_data = get_central_directory()
    zip_entries = parse_central_directory(cd_data)
    print(f'Parsed zip entries for {len(zip_entries)} species.')

    freq_pts_hz = compute_mel_frequencies(224)
    freq_pts_khz = freq_pts_hz / 1000.0
    time_pts_sec = np.linspace(0.0, 1.0, 224)

    species_results = []
    
    # Target species list
    target_species = list(SPECIES_METADATA.keys())

    for sp in target_species:
        print(f'\nProcessing species: {sp}')
        sp_meta = SPECIES_METADATA.get(sp, {'common': sp, 'category': 'Bird Vocalization', 'freq_band': '1 - 6 kHz', 'description': ''})
        
        # Look for matching zip entries
        # Check alternative folder names like 'Anas (Mareca) strepera' vs 'Anas strepera'
        matched_sp = sp
        if matched_sp not in zip_entries:
            for k in zip_entries.keys():
                if sp.split()[-1] in k:
                    matched_sp = k
                    break
        
        if matched_sp not in zip_entries:
            print(f'Warning: No zip entries found for {sp}')
            continue
            
        sp_entries = zip_entries[matched_sp]
        print(f'  Found {len(sp_entries)} spectrogram files.')
        
        # Get metadata rows for this species
        sub_df = df[df['species'] == sp]
        if len(sub_df) == 0:
            # Try fuzzy match
            sub_df = df[df['species'].str.contains(sp.split()[-1])]

        # Select up to 3 candidate samples to find the one with clearest vocalization
        best_candidate = None
        best_peak_contrast = -999.0
        best_arr = None
        best_meta_row = None

        candidates = sp_entries[:min(6, len(sp_entries))]
        for entry in candidates:
            try:
                arr = fetch_single_npy(entry)
                # Vocal contrast: max dB - median dB
                contrast = float(np.max(arr) - np.median(arr))
                # Also check that peak dB is strong (> -25 dB)
                peak_db = float(np.max(arr))
                score = contrast + (peak_db * 0.5)
                if score > best_peak_contrast:
                    best_peak_contrast = score
                    best_candidate = entry
                    best_arr = arr
            except Exception as e:
                print(f'  Error loading {entry["name"]}: {e}')

        if best_candidate is None or best_arr is None:
            print(f'  Could not load any spectrogram for {sp}')
            continue

        print(f'  Selected best sample: {best_candidate["filename"]} (contrast score: {best_peak_contrast:.1f})')

        # Find row in metadata
        fname = best_candidate['filename']
        matched_row = sub_df[sub_df['spectrogram_name'] == fname]
        if len(matched_row) > 0:
            row = matched_row.iloc[0]
            audio_name = str(row['audio_name'])
            sec_i = float(row['sec_i'])
            sec_f = float(row['sec_f'])
        else:
            audio_name = fname.split('_')[0] + '.mp3'
            sec_i = 0.0
            sec_f = 1.0

        # Try downloading audio slice for this species
        audio_filename = f'{sp.replace(" ", "_")}_{fname.replace(".npy", ".mp3")}'
        audio_path = os.path.join(AUDIO_DIR, audio_filename)
        audio_success = download_and_slice_audio(audio_name, sec_i, sec_f, audio_path)
        audio_rel_url = f'audio/{audio_filename}' if audio_success else None
        print(f'  Audio downloaded: {audio_success}')

        # Compute vocal dynamics
        # best_arr is (224, 224) -> axis 0: freq, axis 1: time
        # Subsample to (56, 56) for smooth 60fps 3D WebGL rendering
        step_f = 4
        step_t = 4
        z_sub = best_arr[::step_f, ::step_t] # (56, 56)
        f_sub_khz = freq_pts_khz[::step_f] # 56
        t_sub_sec = time_pts_sec[::step_t] # 56

        # Dominant frequency contour (highest energy bin at each time step)
        peak_bin_indices = np.argmax(best_arr, axis=0) # 224
        peak_freq_hz = freq_pts_hz[peak_bin_indices]
        peak_freq_khz = freq_pts_khz[peak_bin_indices]
        peak_db = np.max(best_arr, axis=0)

        # Spectral centroid (weighted center of frequency mass)
        linear_power = 10.0 ** (best_arr / 20.0)
        power_sum = np.sum(linear_power, axis=0) + 1e-8
        spectral_centroid_hz = np.sum(linear_power * freq_pts_hz[:, None], axis=0) / power_sum
        spectral_centroid_khz = spectral_centroid_hz / 1000.0

        # Voice Activity Detection (VAD)
        # Bird vocalization typically when peak_db > -45 dB
        vad_mask = (peak_db > -45.0).astype(int).tolist()

        # Summary statistics of bird voice
        active_indices = np.where(peak_db > -45.0)[0]
        if len(active_indices) > 0:
            mean_voice_freq_khz = float(np.mean(peak_freq_khz[active_indices]))
            min_voice_freq_khz = float(np.min(peak_freq_khz[active_indices]))
            max_voice_freq_khz = float(np.max(peak_freq_khz[active_indices]))
            freq_modulation_bandwidth_khz = float(max_voice_freq_khz - min_voice_freq_khz)
        else:
            mean_voice_freq_khz = float(np.mean(peak_freq_khz))
            min_voice_freq_khz = float(np.min(peak_freq_khz))
            max_voice_freq_khz = float(np.max(peak_freq_khz))
            freq_modulation_bandwidth_khz = float(max_voice_freq_khz - min_voice_freq_khz)

        # Prepare 3D trajectory points (t, freq, db)
        trajectory_points = []
        for i in range(len(time_pts_sec)):
            trajectory_points.append({
                'time': round(float(time_pts_sec[i]), 4),
                'peak_freq_khz': round(float(peak_freq_khz[i]), 3),
                'centroid_freq_khz': round(float(spectral_centroid_khz[i]), 3),
                'peak_db': round(float(peak_db[i]), 2),
                'is_active': bool(vad_mask[i])
            })

        species_dict = {
            'species': sp,
            'common_name': sp_meta.get('common', sp),
            'family': sp_meta.get('family', 'Wetland Birds'),
            'category': sp_meta.get('category', 'Vocal Species'),
            'description': sp_meta.get('description', ''),
            'spectrogram_file': best_candidate['filename'],
            'audio_name': audio_name,
            'time_interval': [sec_i, sec_f],
            'audio_url': audio_rel_url,
            'stats': {
                'mean_voice_freq_khz': round(mean_voice_freq_khz, 3),
                'min_voice_freq_khz': round(min_voice_freq_khz, 3),
                'max_voice_freq_khz': round(max_voice_freq_khz, 3),
                'bandwidth_khz': round(freq_modulation_bandwidth_khz, 3),
                'max_peak_db': round(float(np.max(peak_db)), 2),
                'active_ratio': round(float(np.mean(vad_mask)), 2)
            },
            'mesh': {
                'time': [round(float(t), 4) for t in t_sub_sec],
                'freq_khz': [round(float(f), 3) for f in f_sub_khz],
                'z_db': [[round(float(val), 2) for val in row] for row in z_sub.tolist()]
            },
            'trajectory': trajectory_points
        }
        species_results.append(species_dict)

    output_json = os.path.join(DATA_DIR, 'bird_vocalizations.json')
    with open(output_json, 'w', encoding='utf-8') as f:
        json.dump({
            'dataset_name': 'Western Mediterranean Wetlands Bird Dataset',
            'zenodo_record': '7505820',
            'species_count': len(species_results),
            'species': species_results
        }, f, indent=2)
    
    print(f'\nPipeline completed successfully!')
    print(f'Processed {len(species_results)} bird species.')
    print(f'Exported: {output_json} (size: {os.path.getsize(output_json) / 1024:.1f} KB)')

if __name__ == '__main__':
    main()
